#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
ARTIFACT_ROOT="${ARTIFACT_ROOT:-/mnt/project/VLA-AD}"

export RUN_NAME="${RUN_NAME:-stage3_grpo_rloo_selfimit_s16_lr1e4_b2acc4_$(date -u +%Y%m%dT%H%M%SZ)}"
export OUT_ROOT="${OUT_ROOT:-${ARTIFACT_ROOT}/outputs/${RUN_NAME}}"

# Preserve the original-GRPO training recipe. The only algorithmic addition is a
# small low-noise diffusion self-imitation loss on safe, high-reward on-policy
# samples whose reward is above a leave-one-out same-token baseline.
export RUN_TRAIN="${RUN_TRAIN:-0}"
export LAUNCH_EVAL_WATCHERS="${LAUNCH_EVAL_WATCHERS:-1}"
export CACHE_MODE="${CACHE_MODE:-online}"
export KILL_GPU_STRESS="${KILL_GPU_STRESS:-0}"
export LR="${LR:-1e-4}"
